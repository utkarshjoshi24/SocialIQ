"""
SocialIQ ML — Training Pipeline
================================

Trains a DecisionTreeClassifier to predict post performance class (Low / Medium / High)
using ONLY pre-publication features.

FEATURES (pre-publication only — no data leakage):
  Categorical:  platform, content_type, category, day_of_week
  Numerical:    caption_length, hashtags_count, duration_seconds, posting_hour

TARGET:
  performance_class ∈ {Low, Medium, High}
  Created from engagement_rate using 33rd/66th percentile thresholds computed
  on the TRAINING SET ONLY (thresholds are saved with the model artifact to
  prevent test-set information leaking into labelling).

MODEL:
  sklearn DecisionTreeClassifier(max_depth=8, min_samples_leaf=5, random_state=42)
  Wrapped in a Pipeline with OneHotEncoder for categoricals.

EVALUATION:
  Accuracy, per-class Precision / Recall / F1, macro-averaged F1, Confusion Matrix.
  Saved to analytics/models/metrics.json.

USAGE:
  cd analytics/
  ../venv/bin/python train_model.py
"""

import os
import sys
import json
import hashlib
import platform
import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.preprocessing import OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
FEATURE_COLS_CATEGORICAL = ['platform', 'content_type', 'category', 'day_of_week']
FEATURE_COLS_NUMERICAL = ['caption_length', 'hashtags_count', 'duration_seconds', 'posting_hour']
ALL_FEATURES = FEATURE_COLS_CATEGORICAL + FEATURE_COLS_NUMERICAL
TARGET_COL = 'performance_class'
RANDOM_STATE = 42
TEST_SIZE = 0.20

# Outcome columns that MUST NEVER be used as features (data-leakage guard)
OUTCOME_COLUMNS = frozenset([
    'views', 'likes', 'comments', 'shares', 'saves',
    'reach', 'engagement_rate', 'engagement_total',
])

MODELS_DIR = os.path.join(os.path.dirname(__file__), 'models')
MODEL_PATH = os.path.join(MODELS_DIR, 'model.pkl')
METRICS_PATH = os.path.join(MODELS_DIR, 'metrics.json')
THRESHOLDS_PATH = os.path.join(MODELS_DIR, 'thresholds.json')

CLASS_ORDER = ['Low', 'Medium', 'High']


# ---------------------------------------------------------------------------
# 1. Load data
# ---------------------------------------------------------------------------
def load_training_data() -> pd.DataFrame:
    """
    Loads training data.  Priority order:
      1. analytics/data/synthetic_training_data.csv  (generated by generate_training_data.py)
      2. Any CSV passed as first CLI argument.
    """
    csv_path = os.path.join(os.path.dirname(__file__), 'data', 'synthetic_training_data.csv')

    if len(sys.argv) > 1 and os.path.isfile(sys.argv[1]):
        csv_path = sys.argv[1]

    if not os.path.isfile(csv_path):
        # Auto-generate if missing
        print("[ML] Training CSV not found — generating synthetic dataset…")
        from generate_training_data import save_csv
        csv_path = save_csv(csv_path)

    df = pd.read_csv(csv_path)
    df.attrs['source_path'] = csv_path
    print(f"[ML] Loaded {len(df)} records from {csv_path}")
    return df


def _sha256(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(65536), b''):
            digest.update(block)
    return digest.hexdigest()


def build_model_info(df: pd.DataFrame) -> dict:
    """
    Provenance saved with the model so a prediction can be traced to the exact
    artifact, data and library versions. model_version is the first 12 hex
    characters of model.pkl's SHA-256 (no timestamps, so retraining with the
    same data and libraries reproduces the same version).
    """
    import numpy
    import sklearn
    source = df.attrs.get('source_path')
    return {
        'model_version': _sha256(MODEL_PATH)[:12],
        'dataset': {
            'file': os.path.basename(source) if source else None,
            'rows': int(len(df)),
            'sha256': _sha256(source) if source and os.path.isfile(source) else None,
        },
        'environment': {
            'python': platform.python_version(),
            'scikit_learn': sklearn.__version__,
            'pandas': pd.__version__,
            'numpy': numpy.__version__,
            'joblib': joblib.__version__,
        },
    }


# ---------------------------------------------------------------------------
# 2. Create target labels (percentile-based, computed on training split)
# ---------------------------------------------------------------------------
def create_target_labels(
    engagement_rates: pd.Series,
    q_low: float = None,
    q_high: float = None,
) -> tuple:
    """
    Assign performance_class using engagement_rate percentile thresholds.

    If thresholds are not supplied, they are computed as the 33rd and 66th
    percentiles of the provided series (should be TRAINING data only).

    Returns:
        (labels: pd.Series, q_low: float, q_high: float)
    """
    if q_low is None or q_high is None:
        q_low = float(np.percentile(engagement_rates.dropna(), 33))
        q_high = float(np.percentile(engagement_rates.dropna(), 66))

    def _assign(val):
        if val >= q_high:
            return 'High'
        elif val >= q_low:
            return 'Medium'
        return 'Low'

    labels = engagement_rates.apply(_assign)
    return labels, q_low, q_high


# ---------------------------------------------------------------------------
# 3. Data-quality checks
# ---------------------------------------------------------------------------
def run_quality_checks(df: pd.DataFrame) -> dict:
    """
    Returns a dict of quality-check results (printed and saved with metrics).
    """
    checks = {}

    # Missing values
    missing = df[ALL_FEATURES].isnull().sum().to_dict()
    checks['missing_values'] = {k: int(v) for k, v in missing.items()}

    # Duplicates
    n_dupes = int(df.duplicated(subset=['post_id']).sum()) if 'post_id' in df.columns else 0
    checks['duplicate_records'] = n_dupes

    # Data leakage guard — verify no outcome column is in features
    leaked = [c for c in ALL_FEATURES if c in OUTCOME_COLUMNS]
    checks['data_leakage_detected'] = leaked
    if leaked:
        raise RuntimeError(f"DATA LEAKAGE: outcome columns found in features: {leaked}")

    # Class distribution (computed later, placeholder)
    checks['class_distribution'] = {}

    # Dataset size
    checks['total_records'] = int(len(df))
    checks['dataset_size_warning'] = (
        'Dataset has fewer than 100 records — model may overfit or be unreliable.'
        if len(df) < 100 else None
    )

    return checks


# ---------------------------------------------------------------------------
# 4. Build pipeline
# ---------------------------------------------------------------------------
def build_pipeline() -> Pipeline:
    """
    Constructs a scikit-learn Pipeline:
      1. OneHotEncoder for categorical features (handle_unknown='ignore')
      2. Passthrough for numerical features
      3. DecisionTreeClassifier with controlled depth to reduce overfitting
    """
    preprocessor = ColumnTransformer(
        transformers=[
            ('cat', OneHotEncoder(handle_unknown='ignore', sparse_output=False), FEATURE_COLS_CATEGORICAL),
            ('num', 'passthrough', FEATURE_COLS_NUMERICAL),
        ]
    )

    pipeline = Pipeline(steps=[
        ('preprocessor', preprocessor),
        ('classifier', DecisionTreeClassifier(
            max_depth=8,
            min_samples_leaf=5,
            min_samples_split=10,
            class_weight='balanced',
            random_state=RANDOM_STATE,
        )),
    ])

    return pipeline


# ---------------------------------------------------------------------------
# 5. Evaluate
# ---------------------------------------------------------------------------
def evaluate_model(pipeline: Pipeline, X_test: pd.DataFrame, y_test: pd.Series) -> dict:
    """
    Runs prediction on the test set and computes all required metrics.
    """
    y_pred = pipeline.predict(X_test)

    acc = float(accuracy_score(y_test, y_pred))
    prec_macro = float(precision_score(y_test, y_pred, average='macro', zero_division=0))
    rec_macro = float(recall_score(y_test, y_pred, average='macro', zero_division=0))
    f1_macro = float(f1_score(y_test, y_pred, average='macro', zero_division=0))
    cm = confusion_matrix(y_test, y_pred, labels=CLASS_ORDER).tolist()
    report = classification_report(y_test, y_pred, labels=CLASS_ORDER, output_dict=True, zero_division=0)

    metrics = {
        'accuracy': round(acc, 4),
        'precision_macro': round(prec_macro, 4),
        'recall_macro': round(rec_macro, 4),
        'f1_macro': round(f1_macro, 4),
        'confusion_matrix': {
            'labels': CLASS_ORDER,
            'matrix': cm,
        },
        'per_class': {},
    }

    for cls in CLASS_ORDER:
        if cls in report:
            metrics['per_class'][cls] = {
                'precision': round(report[cls]['precision'], 4),
                'recall': round(report[cls]['recall'], 4),
                'f1': round(report[cls]['f1-score'], 4),
                'support': int(report[cls]['support']),
            }

    return metrics


# ---------------------------------------------------------------------------
# 6. Feature importance
# ---------------------------------------------------------------------------
def extract_feature_importance(pipeline: Pipeline) -> dict:
    """
    Extracts feature importances from the trained DecisionTree.
    Returns a dict mapping feature names → importance values.
    """
    tree = pipeline.named_steps['classifier']
    preprocessor = pipeline.named_steps['preprocessor']

    # Get feature names after one-hot encoding
    cat_encoder = preprocessor.named_transformers_['cat']
    cat_features = cat_encoder.get_feature_names_out(FEATURE_COLS_CATEGORICAL).tolist()
    all_feature_names = cat_features + FEATURE_COLS_NUMERICAL

    importances = tree.feature_importances_
    importance_dict = {}
    for name, imp in zip(all_feature_names, importances):
        importance_dict[name] = round(float(imp), 4)

    # Sort by importance descending
    importance_dict = dict(sorted(importance_dict.items(), key=lambda x: x[1], reverse=True))
    return importance_dict


# ---------------------------------------------------------------------------
# 7. Overfitting check
# ---------------------------------------------------------------------------
def check_overfitting(pipeline: Pipeline, X_train, y_train, X_test, y_test) -> dict:
    """
    Compares training accuracy vs test accuracy to flag overfitting.
    """
    train_acc = float(accuracy_score(y_train, pipeline.predict(X_train)))
    test_acc = float(accuracy_score(y_test, pipeline.predict(X_test)))
    gap = train_acc - test_acc

    return {
        'train_accuracy': round(train_acc, 4),
        'test_accuracy': round(test_acc, 4),
        'overfit_gap': round(gap, 4),
        'overfitting_flag': gap > 0.10,
        'note': (
            'Train-test accuracy gap > 10%: possible overfitting. '
            'Consider reducing max_depth or increasing min_samples_leaf.'
            if gap > 0.10 else
            'Train-test gap within acceptable range.'
        ),
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    print("=" * 60)
    print("SocialIQ — ML Performance Prediction Training Pipeline")
    print("=" * 60)

    # 1. Load data
    df = load_training_data()

    # 2. Prepare features
    # Ensure day_of_week exists
    if 'day_of_week' not in df.columns and 'date' in df.columns:
        df['day_of_week'] = pd.to_datetime(df['date'], errors='coerce').dt.day_name().fillna('Monday')

    # Verify required columns
    missing_features = [c for c in ALL_FEATURES if c not in df.columns]
    if missing_features:
        print(f"[ML ERROR] Missing feature columns: {missing_features}")
        sys.exit(1)

    if 'engagement_rate' not in df.columns:
        print("[ML ERROR] engagement_rate column required for target labelling.")
        sys.exit(1)

    # 3. Quality checks
    quality = run_quality_checks(df)
    print(f"\n[ML] Dataset size: {quality['total_records']} records")
    if quality['dataset_size_warning']:
        print(f"[ML WARNING] {quality['dataset_size_warning']}")
    print(f"[ML] Duplicate post_ids: {quality['duplicate_records']}")
    print(f"[ML] Data leakage check: {'PASS' if not quality['data_leakage_detected'] else 'FAIL'}")

    # 4. Drop duplicates
    if 'post_id' in df.columns:
        df = df.drop_duplicates(subset=['post_id'])

    # Fill missing feature values
    for col in FEATURE_COLS_NUMERICAL:
        df[col] = pd.to_numeric(df[col], errors='coerce').fillna(0)
    for col in FEATURE_COLS_CATEGORICAL:
        df[col] = df[col].fillna('Unknown').astype(str)

    # 5. Train/test split BEFORE creating target labels (prevents label leakage)
    X = df[ALL_FEATURES].copy()
    er = df['engagement_rate'].copy()

    X_train, X_test, er_train, er_test = train_test_split(
        X, er, test_size=TEST_SIZE, random_state=RANDOM_STATE,
    )

    # 6. Create target labels using TRAINING thresholds only
    y_train, q_low, q_high = create_target_labels(er_train)
    y_test, _, _ = create_target_labels(er_test, q_low=q_low, q_high=q_high)

    print(f"\n[ML] Performance class thresholds (from training set):")
    print(f"     Low:    engagement_rate < {q_low:.2f}%")
    print(f"     Medium: {q_low:.2f}% ≤ engagement_rate < {q_high:.2f}%")
    print(f"     High:   engagement_rate ≥ {q_high:.2f}%")

    # Class distribution
    train_dist = y_train.value_counts().to_dict()
    test_dist = y_test.value_counts().to_dict()
    quality['class_distribution'] = {
        'train': {k: int(v) for k, v in train_dist.items()},
        'test': {k: int(v) for k, v in test_dist.items()},
    }
    print(f"\n[ML] Class distribution (train): {train_dist}")
    print(f"[ML] Class distribution (test):  {test_dist}")

    # 7. Build and train pipeline
    print("\n[ML] Training DecisionTreeClassifier…")
    pipeline = build_pipeline()
    pipeline.fit(X_train, y_train)
    print("[ML] Training complete.")

    # 8. Evaluate
    metrics = evaluate_model(pipeline, X_test, y_test)
    print(f"\n[ML] Test Accuracy:      {metrics['accuracy']:.4f}")
    print(f"[ML] Precision (macro): {metrics['precision_macro']:.4f}")
    print(f"[ML] Recall (macro):    {metrics['recall_macro']:.4f}")
    print(f"[ML] F1 Score (macro):  {metrics['f1_macro']:.4f}")
    print(f"\n[ML] Confusion Matrix (rows=actual, cols=predicted):")
    print(f"     Labels: {CLASS_ORDER}")
    for row in metrics['confusion_matrix']['matrix']:
        print(f"     {row}")

    # Per-class metrics
    print(f"\n[ML] Per-class metrics:")
    for cls in CLASS_ORDER:
        pc = metrics['per_class'].get(cls, {})
        print(f"     {cls:7s}  P={pc.get('precision', 0):.3f}  R={pc.get('recall', 0):.3f}  F1={pc.get('f1', 0):.3f}  Support={pc.get('support', 0)}")

    # 9. Feature importance
    importances = extract_feature_importance(pipeline)
    print(f"\n[ML] Top 10 feature importances:")
    for i, (feat, imp) in enumerate(importances.items()):
        if i >= 10:
            break
        print(f"     {feat:40s} {imp:.4f}")

    # 10. Overfitting check
    overfit = check_overfitting(pipeline, X_train, y_train, X_test, y_test)
    print(f"\n[ML] Overfitting check:")
    print(f"     Train accuracy: {overfit['train_accuracy']:.4f}")
    print(f"     Test accuracy:  {overfit['test_accuracy']:.4f}")
    print(f"     Gap:            {overfit['overfit_gap']:.4f}")
    print(f"     Flag:           {'⚠ OVERFITTING' if overfit['overfitting_flag'] else '✓ OK'}")
    print(f"     {overfit['note']}")

    # 11. Save artifacts
    os.makedirs(MODELS_DIR, exist_ok=True)

    joblib.dump(pipeline, MODEL_PATH)
    print(f"\n[ML] Model saved to {MODEL_PATH}")

    # Save thresholds
    thresholds = {
        'q_low': round(q_low, 4),
        'q_high': round(q_high, 4),
        'method': 'percentile-based (33rd / 66th) on training engagement_rate',
        'class_definitions': {
            'Low': f'engagement_rate < {q_low:.4f}',
            'Medium': f'{q_low:.4f} <= engagement_rate < {q_high:.4f}',
            'High': f'engagement_rate >= {q_high:.4f}',
        },
    }
    with open(THRESHOLDS_PATH, 'w') as f:
        json.dump(thresholds, f, indent=2)
    print(f"[ML] Thresholds saved to {THRESHOLDS_PATH}")

    # Save metrics
    full_metrics = {
        'model': 'DecisionTreeClassifier',
        'model_info': build_model_info(df),
        'features': ALL_FEATURES,
        'target': TARGET_COL,
        'random_state': RANDOM_STATE,
        'test_size': TEST_SIZE,
        'thresholds': thresholds,
        'evaluation': metrics,
        'feature_importances': importances,
        'overfitting_check': overfit,
        'quality_checks': quality,
        'limitations': [],
    }

    if quality['total_records'] < 100:
        full_metrics['limitations'].append(
            f"Dataset has only {quality['total_records']} records. "
            "Model performance may not generalize well to real-world data."
        )
    if overfit['overfitting_flag']:
        full_metrics['limitations'].append(
            f"Train-test accuracy gap of {overfit['overfit_gap']:.2%} suggests overfitting."
        )

    with open(METRICS_PATH, 'w') as f:
        json.dump(full_metrics, f, indent=2)
    print(f"[ML] Metrics saved to {METRICS_PATH}")

    print("\n" + "=" * 60)
    print("Training pipeline complete.")
    print("=" * 60)
    return full_metrics


if __name__ == '__main__':
    main()
